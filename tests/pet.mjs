import assert from 'node:assert/strict';
import {actionCues,resolveCue,actionSoundAllowed,PetSound} from '../web/pet-sound.mjs';
import {isDrag,classifyClick,clickCue,clickOpensMain,hoverDue,DRAG_THRESHOLD_PX,HOVER_COOLDOWN_MS} from '../web/pet-gesture.mjs';
assert.equal(resolveCue('step').length,2);
