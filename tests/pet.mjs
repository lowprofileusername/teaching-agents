assert.equal(actionSoundAllowed(on,'greet'),true);
assert.equal(actionSoundAllowed({...on,enabled:false},'greet'),false);
assert.equal(actionSoundAllowed({...on,quiet:true},'greet'),false);
assert.equal(actionSoundAllowed({...on,speaking:true},'greet'),false);
assert.equal(actionSoundAllowed({...on,generating:true},'step'),false);
assert.equal(actionSoundAllowed(on,'nope'),false);
assert.equal(classifyClick(1),'single');
assert.equal(classifyClick(2),'double');
assert.equal(classifyClick(3),'multi');
assert.equal(classifyClick(9),'multi');
assert.equal(clickCue('single'),'greet');
assert.equal(clickCue('double'),'notice');
assert.equal(clickCue('multi'),'celebrate');
assert.equal(clickOpensMain('single'),true);
assert.equal(clickOpensMain('double'),false);
assert.equal(isDrag(3,4),false);
assert.equal(isDrag(3,5),true);
assert.equal(DRAG_THRESHOLD_PX,5);
assert.equal(hoverDue(0,HOVER_COOLDOWN_MS),true);
assert.equal(hoverDue(0,HOVER_COOLDOWN_MS-1),false);
