import assert from 'node:assert/strict';
import {sideEffectState,recoveryMode,detectUnfinished,resumeNotice,resumeContextNote} from '../web/task-resume.mjs';
assert.equal(detectUnfinished(null),null);
assert.equal(detectUnfinished({jobState:'done',conversation:[{role:'user',text:'hi',status:'complete'}]}),null);
const interrupted={jobState:'interrupted',conversation:[{role:'user',text:'学生二稿改好了吗？',status:'complete'},{role:'assistant',text:'',status:'generating'}]};
const slot=detectUnfinished(interrupted);
assert.ok(slot);
assert.equal(slot.lastTask,'学生二稿改好了吗？');
assert.equal(slot.sideEffectState,'none');
assert.equal(slot.recoveryMode,'resume_context');
assert.match(resumeNotice(slot),/没有修改工作区/);
assert.equal(sideEffectState({uploaded:{name:'a.docx'}}),'local_committed');
assert.equal(sideEffectState({reviewItems:[{id:'p1'}]}),'local_committed');
assert.equal(sideEffectState({conversation:[{builder_plan:{kind:'report'}}]}),'local_committed');
assert.equal(sideEffectState({conversation:[]}), 'none');
assert.equal(recoveryMode('local_committed'),'requires_review');
assert.equal(recoveryMode('none'),'resume_context');
const reviewSlot=detectUnfinished({jobState:'running',uploaded:{name:'a.docx'},conversation:[{role:'user',text:'改报告'}]});
assert.equal(reviewSlot.recoveryMode,'requires_review');
assert.match(resumeNotice(reviewSlot),/需要审阅/);
assert.match(resumeNotice(reviewSlot),/不会重试该操作/);
assert.match(resumeContextNote(reviewSlot),/不要仅因任务恢复就重复执行/);
assert.match(resumeContextNote(reviewSlot),/改报告/);
const genSlot=detectUnfinished({conversation:[{role:'user',text:'q'},{role:'assistant',status:'generating'}]});
assert.ok(genSlot);
console.log('PASS unfinished-task detection, side-effect classification and resume-only context');